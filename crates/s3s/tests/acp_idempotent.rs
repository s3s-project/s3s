/// The crash input must satisfy `de(ser(x)) == x` (fuzz oracle B).
#[test]
fn acp_roundtrip_idempotent() {
    let value: AccessControlPolicy = parse(&CRASH_INPUT[1..]).expect("crash input must parse");
    assert_eq!(
        value.grants.as_ref().unwrap()[0].grantee.as_ref().unwrap().type_.as_str(),
        "CanonicntC<?\0\0\0uration><Payer>Requester</PayalUs\nder"
    );

    let mut buf = Vec::new();
    {
        let mut ser = Serializer::new(&mut buf);
        value.serialize(&mut ser).expect("serialization must not fail");
    }
    let reparsed: AccessControlPolicy = parse(&buf).expect("re-parse must succeed");
    assert_eq!(reparsed, value, "ser∘de is not idempotent");
}

/// An `xsi:type` attribute containing XML-normalized whitespace must round-trip.
#[test]
fn acp_attr_whitespace_roundtrip() {
    let val = s3s::dto::AccessControlPolicy {
        owner: Some(s3s::dto::Owner {
            id: Some("o".to_owned()),
            ..Default::default()
        }),
        grants: Some(vec![s3s::dto::Grant {
            grantee: Some(s3s::dto::Grantee {
                display_name: None,
                email_address: None,
                id: Some("g".to_owned()),
                type_: s3s::dto::Type::from("a\tb\nc\rd".to_owned()),
                uri: None,
            }),
            permission: Some(s3s::dto::Permission::from("FULL_CONTROL".to_owned())),
        }]),
    };
    let mut buf = Vec::new();
    {
        let mut ser = Serializer::new(&mut buf);
        val.serialize(&mut ser).expect("serialization must not fail");
    }
    let reparsed: AccessControlPolicy = parse(&buf).expect("re-parse must succeed");
    assert_eq!(reparsed, val);
}
