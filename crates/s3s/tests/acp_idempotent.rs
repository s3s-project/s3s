//! Regression test for the fuzz crash `AccessControlPolicy: ser∘de is not idempotent`.
//!
//! The crash input (311 bytes, `data[0]` = type selector for
//! `AccessControlPolicy`) contains a `xsi:type` attribute value with a
//! `&#10;` character reference. Before the fix, the serializer wrote the
//! decoded `\n` literally into the attribute, and XML attribute normalization
//! replaced it with a space on re-parse, breaking idempotence.

use s3s::dto::AccessControlPolicy;
use s3s::xml::{Deserialize, Deserializer, Serialize, Serializer};

fn parse<T: for<'x> Deserialize<'x>>(bytes: &[u8]) -> Result<T, s3s::xml::DeError> {
    let mut d = Deserializer::new(bytes);
    let ans = T::deserialize(&mut d)?;
    d.expect_eof()?;
    Ok(ans)
}

